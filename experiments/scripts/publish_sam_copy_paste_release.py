"""Stage a verified SAM augmentation release into a full Kaggle dataset snapshot.

Kaggle's ``datasets version`` uploads the files supplied locally; it must not be
pointed at the augmentation delta alone when the intention is to preserve the
existing MTC dataset. This command copies the verified train-only release as a
new top-level directory, leaving all base files and validation data intact.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path


def _pairs(directory: Path) -> tuple[set[str], set[str]]:
    """Return image and label stems from a standard train-only release."""
    images = {path.stem for path in (directory / "images" / "train").glob("*.jpg")}
    labels = {path.stem for path in (directory / "labels" / "train").glob("*.txt")}
    return images, labels


def stage_release(release: Path, dataset_root: Path) -> Path:
    """Copy a validated release into a complete MTC snapshot.

    Args:
        release: ``sam_copy_paste_<run_id>`` directory generated by production.
        dataset_root: Downloaded full MTC dataset to be versioned on Kaggle.

    Returns:
        New top-level release directory inside ``dataset_root``.

    Raises:
        FileNotFoundError: If the release or base dataset contract is incomplete.
        ValueError: If validation evidence or image/label pairing is invalid.
        FileExistsError: If the target release name already exists.
    """
    required_base = (
        dataset_root / "split_metadata.csv",
        dataset_root / "train_resized" / "train",
        dataset_root / "smart_lama_corrected" / "train",
        dataset_root / "yolo_obb_labels" / "train",
    )
    if not release.is_dir() or not all(path.exists() for path in required_base):
        raise FileNotFoundError("Release or full MTC dataset snapshot is incomplete")
    manifest_path = release / "release_manifest.json"
    if not manifest_path.is_file():
        raise FileNotFoundError("release_manifest.json is required")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if not manifest.get("validation", {}).get("validation_unchanged"):
        raise ValueError("Release does not prove that validation is unchanged")
    image_stems, label_stems = _pairs(release)
    if not image_stems or image_stems != label_stems:
        raise ValueError("Release image/label stems are missing or mismatched")
    if (release / "images" / "val").exists() or (release / "labels" / "val").exists():
        raise ValueError("Refusing a release containing validation files")
    destination = dataset_root / release.name
    if destination.exists():
        raise FileExistsError(f"Release already exists in dataset snapshot: {destination}")
    shutil.copytree(release, destination)
    return destination


def main() -> int:
    """Stage one release and print the exact directory ready for Kaggle versioning."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release", required=True, type=Path)
    parser.add_argument("--dataset-root", required=True, type=Path)
    args = parser.parse_args()
    destination = stage_release(args.release, args.dataset_root)
    print(destination)
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI wrapper
    raise SystemExit(main())
